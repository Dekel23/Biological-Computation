/** Apply <html lang/dir> so the whole document (scrollbars, inputs, portals) flips. */
export function applyDocumentDirection(lng) {
  const conf = LANGUAGES[lng] ?? LANGUAGES.en
  document.documentElement.lang = lng
  document.documentElement.dir = conf.dir
}

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources: { en: { translation: en }, he: { translation: he } },
    fallbackLng: 'en',
    supportedLngs: ['en', 'he'],
    nonExplicitSupportedLngs: true,
    // English by default: only an explicit choice (stored in localStorage) switches language.
    detection: { order: ['localStorage'], lookupLocalStorage: 'lang', caches: ['localStorage'] },
    interpolation: { escapeValue: false },
    returnNull: false,
  })

applyDocumentDirection(i18n.resolvedLanguage || 'en')
i18n.on('languageChanged', applyDocumentDirection)

export default i18n
